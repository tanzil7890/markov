import { posixCurlCommand } from '../agent-hooks/hook-post-command'
import { buildWindowsAgentHookPostCommand } from '../agent-hooks/installer-utils'
import {
  buildPosixHookPayloadCapture,
  buildPosixHookSpoolLines,
  buildWindowsHookEnvironmentGuardLines
} from '../agent-hooks/hook-stdin-contract'

export type CommandCodeManagedScriptTarget = 'local' | 'posix'

export function buildCommandCodeManagedScript(
  target: CommandCodeManagedScriptTarget = 'local'
): string {
  if (target === 'local' && process.platform === 'win32') {
    return [
      '@echo off',
      'setlocal',
      'if "%MARKOV_AGENT_HOOK_PORT%"=="" if defined MARKOV_AGENT_HOOK_ENDPOINT if exist "%MARKOV_AGENT_HOOK_ENDPOINT%" call "%MARKOV_AGENT_HOOK_ENDPOINT%" 2>nul',
      'if "%MARKOV_AGENT_HOOK_TOKEN%"=="" if not "%MARKOV_AGENT_HOOK_PORT%"=="" call :sourceEndpointByPort',
      ...buildWindowsHookEnvironmentGuardLines(),
      buildWindowsAgentHookPostCommand('command-code'),
      'exit /b 0',
      ':sourceEndpointByPort',
      'if not defined APPDATA exit /b 0',
      'if exist "%APPDATA%\\markov-dev\\agent-hooks" for /r "%APPDATA%\\markov-dev\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      // Per-worktree `pnpm dev` profiles live one level down; FOR /R cannot take a FOR variable as its root.
      'if "%MARKOV_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\markov-dev-wt" for /d %%P in ("%APPDATA%\\markov-dev-wt\\*") do call :scanEndpointDir "%%~fP\\agent-hooks"',
      'if "%MARKOV_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\markov\\agent-hooks" for /r "%APPDATA%\\markov\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':scanEndpointDir',
      'if not "%MARKOV_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'if exist "%~1" for /r "%~1" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':maybeSourceEndpoint',
      'if not "%MARKOV_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'for /f "tokens=2 delims==" %%P in (\'findstr /b /c:"set MARKOV_AGENT_HOOK_PORT=" "%~1" 2^>nul\') do if "%%P"=="%MARKOV_AGENT_HOOK_PORT%" call "%~1" 2>nul',
      'exit /b 0',
      ''
    ].join('\r\n')
  }

  return [
    '#!/bin/sh',
    ...buildPosixHookPayloadCapture(),
    ...buildPosixHookSpoolLines('command-code'),
    '__markov_read_ancestor_var() {',
    '  __markov_name="$1"',
    '  __markov_pid="${PPID:-}"',
    '  while [ -n "$__markov_pid" ] && [ "$__markov_pid" != "0" ] && [ "$__markov_pid" != "1" ]; do',
    '    __markov_value=""',
    '    if [ -r "/proc/$__markov_pid/environ" ]; then',
    '      __markov_value=$(tr "\\000" "\\n" < "/proc/$__markov_pid/environ" 2>/dev/null | sed -n "s/^${__markov_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -z "$__markov_value" ]; then',
    '      __markov_value=$(ps eww -p "$__markov_pid" -o command= 2>/dev/null | tr " " "\\n" | sed -n "s/^${__markov_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -n "$__markov_value" ]; then',
    '      printf "%s\\n" "$__markov_value"',
    '      return 0',
    '    fi',
    '    __markov_pid=$(ps -o ppid= -p "$__markov_pid" 2>/dev/null | tr -d " ")',
    '  done',
    '  return 1',
    '}',
    '__markov_fill_from_ancestor() {',
    '  __markov_name="$1"',
    '  case "$__markov_name" in',
    '    MARKOV_AGENT_HOOK_ENDPOINT) [ -z "${MARKOV_AGENT_HOOK_ENDPOINT:-}" ] || return 0 ;;',
    '    MARKOV_AGENT_HOOK_PORT) [ -z "${MARKOV_AGENT_HOOK_PORT:-}" ] || return 0 ;;',
    '    MARKOV_AGENT_HOOK_TOKEN) [ -z "${MARKOV_AGENT_HOOK_TOKEN:-}" ] || return 0 ;;',
    '    MARKOV_AGENT_HOOK_ENV) [ -z "${MARKOV_AGENT_HOOK_ENV:-}" ] || return 0 ;;',
    '    MARKOV_AGENT_HOOK_VERSION) [ -z "${MARKOV_AGENT_HOOK_VERSION:-}" ] || return 0 ;;',
    '    MARKOV_PANE_KEY) [ -z "${MARKOV_PANE_KEY:-}" ] || return 0 ;;',
    '    MARKOV_TAB_ID) [ -z "${MARKOV_TAB_ID:-}" ] || return 0 ;;',
    '    MARKOV_WORKTREE_ID) [ -z "${MARKOV_WORKTREE_ID:-}" ] || return 0 ;;',
    '    MARKOV_AGENT_LAUNCH_TOKEN) [ -z "${MARKOV_AGENT_LAUNCH_TOKEN:-}" ] || return 0 ;;',
    '    *) return 0 ;;',
    '  esac',
    '  __markov_value=$(__markov_read_ancestor_var "$__markov_name") || return 0',
    '  [ -n "$__markov_value" ] && export "$__markov_name=$__markov_value"',
    '}',
    '__markov_endpoint_value() {',
    '  __markov_endpoint_name="$1"',
    '  __markov_endpoint_path="$2"',
    '  sed -n "s/^${__markov_endpoint_name}=//p" "$__markov_endpoint_path" 2>/dev/null | head -n 1',
    '}',
    '__markov_fill_from_endpoint_file() {',
    '  __markov_endpoint_path="$1"',
    '  [ -r "$__markov_endpoint_path" ] || return 0',
    '  __markov_endpoint_port=$(__markov_endpoint_value MARKOV_AGENT_HOOK_PORT "$__markov_endpoint_path")',
    '  if [ -n "${MARKOV_AGENT_HOOK_PORT:-}" ] && [ -n "$__markov_endpoint_port" ] && [ "$__markov_endpoint_port" != "$MARKOV_AGENT_HOOK_PORT" ]; then',
    '    return 0',
    '  fi',
    '  for __markov_endpoint_name in MARKOV_AGENT_HOOK_PORT MARKOV_AGENT_HOOK_TOKEN MARKOV_AGENT_HOOK_ENV MARKOV_AGENT_HOOK_VERSION; do',
    '    eval "__markov_current=\\${$__markov_endpoint_name:-}"',
    '    [ -z "$__markov_current" ] || continue',
    '    __markov_endpoint_value=$(__markov_endpoint_value "$__markov_endpoint_name" "$__markov_endpoint_path")',
    '    [ -n "$__markov_endpoint_value" ] && export "$__markov_endpoint_name=$__markov_endpoint_value"',
    '  done',
    '}',
    '# Recover pane/hook metadata from the parent TUI after Command Code sanitizes hook env.',
    'for __markov_name in MARKOV_AGENT_HOOK_ENDPOINT MARKOV_AGENT_HOOK_PORT MARKOV_AGENT_HOOK_TOKEN MARKOV_AGENT_HOOK_ENV MARKOV_AGENT_HOOK_VERSION MARKOV_PANE_KEY MARKOV_TAB_ID MARKOV_WORKTREE_ID MARKOV_AGENT_LAUNCH_TOKEN; do',
    '  __markov_fill_from_ancestor "$__markov_name"',
    'done',
    'if [ -n "$MARKOV_AGENT_HOOK_ENDPOINT" ] && [ -r "$MARKOV_AGENT_HOOK_ENDPOINT" ]; then',
    '  __markov_fill_from_endpoint_file "$MARKOV_AGENT_HOOK_ENDPOINT"',
    'fi',
    '# Recover stripped token metadata by matching the preserved loopback port.',
    'if [ -z "$MARKOV_AGENT_HOOK_TOKEN" ] && [ -n "$MARKOV_AGENT_HOOK_PORT" ]; then',
    '  for endpoint in \\',
    '    "$HOME/Library/Application Support/markov-dev/agent-hooks"/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/markov-dev/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/markov-dev/agent-hooks"/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/markov-dev/agent-hooks/endpoint.env" \\',
    '    "$HOME/Library/Application Support/markov-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/markov-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/markov/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/markov/agent-hooks/endpoint.env"; do',
    '    [ -r "$endpoint" ] || continue',
    '    endpoint_port=$(sed -n "s/^MARKOV_AGENT_HOOK_PORT=//p" "$endpoint" | head -n 1)',
    '    if [ "$endpoint_port" = "$MARKOV_AGENT_HOOK_PORT" ]; then',
    '      __markov_fill_from_endpoint_file "$endpoint"',
    '      break',
    '    fi',
    '  done',
    'fi',
    'if [ -z "$MARKOV_AGENT_HOOK_PORT" ] || [ -z "$MARKOV_AGENT_HOOK_TOKEN" ] || [ -z "$MARKOV_PANE_KEY" ]; then',
    '  spool_hook_event',
    '  exit 0',
    'fi',
    // Bound stalled posts and pipe large payloads through stdin to avoid EDR command-line false positives.
    `printf '%s' "$payload" | ${posixCurlCommand()} -sS -X POST "http://127.0.0.1:\${MARKOV_AGENT_HOOK_PORT}/hook/command-code" \\`,
    '  --connect-timeout 0.5 --max-time 1.5 \\',
    '  -H "Content-Type: application/x-www-form-urlencoded" \\',
    '  -H "X-Markov-Agent-Hook-Token: ${MARKOV_AGENT_HOOK_TOKEN}" \\',
    '  --data-urlencode "paneKey=${MARKOV_PANE_KEY}" \\',
    '  --data-urlencode "tabId=${MARKOV_TAB_ID}" \\',
    '  --data-urlencode "launchToken=${MARKOV_AGENT_LAUNCH_TOKEN}" \\',
    '  --data-urlencode "worktreeId=${MARKOV_WORKTREE_ID}" \\',
    '  --data-urlencode "env=${MARKOV_AGENT_HOOK_ENV}" \\',
    '  --data-urlencode "version=${MARKOV_AGENT_HOOK_VERSION}" \\',
    '  --data-urlencode "payload@-" >/dev/null 2>&1 || spool_hook_event',
    'exit 0',
    ''
  ].join('\n')
}
